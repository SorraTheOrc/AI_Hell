/**
 * Per-wave generation-mode ledger for the shipped default campaign
 * (AH-0MVSE7GWU0074H5I; parent epic AH-0MVI5XXOU00954EA, producer Q3=c').
 *
 * The campaign mixes three generation modes: hand-authored `fixed` waves for
 * identity/showcase pins, deterministic `curve` waves, and seeded `dynamic`
 * filler for per-run variety. The mix used to be implicit in
 * `src/data/difficulty-curves.csv`; this module makes it an explicit,
 * generated contract:
 *
 * - {@link buildModeLedger} derives one row per wave **from the shipped
 *   config** (`defaultDifficultyCurves()`), so the ledger is never a second
 *   hand-maintained copy of the mode data.
 * - {@link renderModeLedgerBlock} renders the Markdown table published in the
 *   Game Design Document's default-campaign note (§3.2). The block is
 *   generated by `scripts/generate-mode-ledger.mjs` and pinned by
 *   `src/waves/modeLedger.test.ts`, so the documented mix cannot drift from
 *   the config.
 *
 * Roles explain *why* a wave holds its mode. They are deliberately a separate
 * axis from the mode itself: the mode always comes from the config, while the
 * role comes from the authored campaign (`LEVELS` mini-boss flags, the shared
 * R1 opening positions and the curated showcase set below).
 *
 * UK English throughout, per the project convention.
 */

import { defaultDifficultyCurves } from '../core/configStore';
import type {
  DifficultyCurveRow,
  DifficultyGeneration,
} from '../core/configTypes';
import { isOpeningWavePosition } from '../core/waveBalance';
import { LEVELS, type LevelDefinition } from './Formations';

/** Why a wave holds its generation mode. */
export type WaveLedgerRole =
  | 'opening'
  | 'dynamic'
  | 'mini-boss'
  | 'showcase'
  | 'filler'
  | 'curve';

/** One row of the generated per-wave mode ledger. */
export interface ModeLedgerRow {
  /** 1-based level number. */
  level: number;
  /** Level theme name from the shipped config. */
  levelName: string;
  /** 1-based wave number within the level. */
  wave: number;
  /** Generation mode read from the shipped config. */
  mode: DifficultyGeneration;
  /** Why the wave holds that mode. */
  role: WaveLedgerRole;
  /** One-line reason shown in the published ledger. */
  reason: string;
}

/**
 * Curated hand-authored showcase waves (level:wave) and the archetype debut
 * each one guarantees. These are the fixed waves that carry a level's
 * identity: every classic-arcade debut and the Orbital Siege/Gauntlet
 * showcases. Shared with the campaign invariants test so the set has one
 * definition.
 */
export const SHOWCASE_WAVES: Readonly<Record<string, string>> = {
  '6:1': 'Space-Invaders `march` debut — hand-authored so the showcase is guaranteed per run seed.',
  '6:2': 'Galaga `capturer` tractor-pull debut — hand-authored so the showcase is guaranteed per run seed.',
  '7:1': 'Centipede chain debut — spawner showcase kept hand-authored so it gates the wave as designed.',
  '7:2': 'Pac-Man `ghosts` pursuit debut — spawner showcase kept hand-authored for a guaranteed pursuit wave.',
  '8:1': 'Frogger lane-traffic debut — non-blocking spawner showcase kept hand-authored.',
  '8:2': 'Robotron `grunt` horde debut — spawner showcase kept hand-authored.',
  '8:3': 'Defender `raider` debut — hand-authored patrol-and-dive showcase.',
  '9:1': 'Orbital Siege showcase — hand-authored mix under the telegraphed orbital-strike hazard.',
  '9:2': 'Orbital Siege pursuit showcase — hand-authored `ghosts` wave under the strike hazard.',
  '10:1': 'Gauntlet showcase — hand-authored raider/capturer/grunt mix that opens the finale.',
};

/** Marker that starts the generated ledger block in the GDD. */
export const MODE_LEDGER_START = '<!-- MODE_LEDGER_START -->';
/** Marker that ends the generated ledger block in the GDD. */
export const MODE_LEDGER_END = '<!-- MODE_LEDGER_END -->';

/** Reason for the curated R1 opening waves. */
const OPENING_REASON =
  'Curated seeded opening — per-run variety on light, non-firing archetypes under R1.';

/** Reason for the level-5 mixed-programme dynamic wave. */
const DYNAMIC_REASON =
  'Mixed-programme dynamic wave — seeded per-run variety outside the onboarding band.';

/** Reason for a level's wave-10 mini-boss. */
const MINI_BOSS_REASON =
  'Hand-authored level mini-boss — must stay byte-identical so the encounter is guaranteed.';

/** Reason for a hand-authored non-showcase filler wave. */
const FILLER_REASON =
  'Hand-authored filler — keeps the authored composition and its parent-AC1 adjacency.';

/** Reason for a curve-generated wave. */
const CURVE_REASON =
  'Curve-generated from `targetDifficulty` — deterministic per run; R1–R4 repairs applied.';

/** Static `LEVELS` definitions keyed by level number. */
function staticLevels(): Map<number, LevelDefinition> {
  return new Map(LEVELS.map((level) => [level.level, level]));
}

/**
 * Derive the ledger row for one configured wave.
 *
 * The mode is always `row.generation`; only the role/reason is classified.
 * Mini-boss and opening positions take precedence over the showcase set (they
 * are stronger design pins), then the curated showcase set, then the mode
 * itself.
 */
function ledgerRow(
  row: DifficultyCurveRow,
  levels: ReadonlyMap<number, LevelDefinition>,
): ModeLedgerRow {
  const key = `${row.level}:${row.wave}`;
  const wave = levels.get(row.level)?.waves[row.wave - 1];
  const base = {
    level: row.level,
    levelName: row.levelName,
    wave: row.wave,
    mode: row.generation ?? 'curve',
  };

  if (isOpeningWavePosition(row.level, row.wave)) {
    return { ...base, role: 'opening', reason: OPENING_REASON };
  }
  if (wave?.miniBoss === true) {
    return { ...base, role: 'mini-boss', reason: MINI_BOSS_REASON };
  }
  if (SHOWCASE_WAVES[key]) {
    return { ...base, role: 'showcase', reason: SHOWCASE_WAVES[key] };
  }
  if (base.mode === 'dynamic') {
    return { ...base, role: 'dynamic', reason: DYNAMIC_REASON };
  }
  if (base.mode === 'curve') {
    return { ...base, role: 'curve', reason: CURVE_REASON };
  }
  return { ...base, role: 'filler', reason: FILLER_REASON };
}

/**
 * Build the per-wave mode ledger from the shipped default curve.
 *
 * Rows are returned in campaign order (level ascending, then wave ascending),
 * exactly as `defaultDifficultyCurves()` produces them. Pass explicit rows to
 * render the ledger for a test fixture.
 */
export function buildModeLedger(
  rows: readonly DifficultyCurveRow[] = defaultDifficultyCurves(),
): ModeLedgerRow[] {
  const levels = staticLevels();
  return rows.map((row) => ledgerRow(row, levels));
}

/** Count rows by generation mode. */
export function countModes(
  rows: readonly ModeLedgerRow[],
): Record<DifficultyGeneration, number> {
  const counts: Record<DifficultyGeneration, number> = {
    curve: 0,
    fixed: 0,
    dynamic: 0,
  };
  for (const row of rows) counts[row.mode] += 1;
  return counts;
}

/** Render the ledger as a Markdown table (one row per wave). */
export function renderModeLedgerTable(
  rows: readonly ModeLedgerRow[] = buildModeLedger(),
): string {
  const lines = [
    '| Level | Wave | Mode | Reason |',
    '|------:|-----:|------|--------|',
  ];
  for (const row of rows) {
    lines.push(
      `| ${row.level} | ${row.wave} | \`${row.mode}\` | ${row.reason} |`,
    );
  }
  return lines.join('\n');
}

/**
 * Render the complete generated ledger block published in the GDD.
 *
 * The block includes the mode counts, the per-wave table and the explicit
 * filler-conversion decision (AC4). It is delimited by
 * {@link MODE_LEDGER_START}/{@link MODE_LEDGER_END} so the generator can
 * replace it in place and the docs guard can compare it exactly.
 */
export function renderModeLedgerBlock(
  rows: readonly ModeLedgerRow[] = buildModeLedger(),
): string {
  const counts = countModes(rows);
  return [
    MODE_LEDGER_START,
    '',
    `The shipped default campaign is **${counts.dynamic} \`dynamic\` + ${counts.curve} \`curve\` + ${counts.fixed} \`fixed\`** waves across 100 waves.`,
    '',
    renderModeLedgerTable(rows),
    '',
    '**Filler conversion decision (documented no-op).** No filler wave is',
    'converted to `dynamic` in this change. The authored data already expresses',
    'the intent for every filler wave (parent AC1 adjacency and the per-level',
    `identity), the ${counts.dynamic} existing \`dynamic\` waves already provide the per-run`,
    'variety the campaign needs, and converting a filler would add seed variance',
    'without a design need. The mix above is therefore final.',
    '',
    MODE_LEDGER_END,
  ].join('\n');
}

/**
 * Extract the generated ledger block from Markdown (including its markers).
 *
 * Returns `null` when the block is absent or its markers are malformed, so a
 * docs guard can fail with a clear message instead of comparing `undefined`.
 */
export function extractModeLedgerBlock(markdown: string): string | null {
  const start = markdown.indexOf(MODE_LEDGER_START);
  const end = markdown.indexOf(MODE_LEDGER_END);
  if (start === -1 || end === -1 || end < start) return null;
  return markdown.slice(start, end + MODE_LEDGER_END.length);
}
